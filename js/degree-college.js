// DEPARTMENT FILTER
// ============================================================

deptList.forEach(item => {

  item.addEventListener("click", () => {

    deptList.forEach(i =>
      i.classList.remove("active")
    );

    item.classList.add("active");

    const dept =
      item.getAttribute("data-dept");

    const filtered =
      dept === "all"
        ? completeStaffData
        : completeStaffData.filter(
            staff => staff.dept === dept
          );

    displayStaff(filtered);

  });

});


// ============================================================
// SEARCH
// ============================================================

searchInput.addEventListener("input", e => {

  const searchTerm =
    e.target.value.toLowerCase().trim();

  const activeDepartment =
    document.querySelector(
      "#deptList .list-group-item.active"
    );

  const dept =
    activeDepartment
      ? activeDepartment.dataset.dept
      : "all";


  const filtered =
    completeStaffData.filter(staff => {

      const matchesDepartment =
        dept === "all" ||
        staff.dept === dept;


      const searchableText = `
        ${staff.name}
        ${staff.role}
        ${staff.email}
        ${staff.qualification}
        ${staff.experience}
        ${staff.expertise}
      `.toLowerCase();


      const matchesSearch =
        searchableText.includes(searchTerm);


      return (
        matchesDepartment &&
        matchesSearch
      );

    });


  displayStaff(filtered);

});


// ============================================================
// COUNTER ANIMATION
// ============================================================

const counters =
  document.querySelectorAll(".counter");

counters.forEach(counter => {

  const target =
    +counter.getAttribute("data-target");

  let count = 0;

  const updateCounter = () => {

    const increment =
      target / 100;

    if (count < target) {

      count += increment;

      counter.innerText =
        Math.ceil(count);

      setTimeout(
        updateCounter,
        20
      );

    } else {

      counter.innerText =
        target;

    }

  };

  updateCounter();

});


