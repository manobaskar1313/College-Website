let completeStaffData = [];

async function loadStaffData() {

  completeStaffData =
    await Promise.all(
      staffData.map(staff =>
        getStaffDetails(staff)
          .then(details => ({
            ...staff,
            ...details
          }))
      )
    );

  displayStaff(completeStaffData);
}


