// GET INFORMATION FROM STAFF PROFILE PAGE
// ============================================================

async function getStaffDetails(staff) {

  const details = {
    name: staff.name,
    role: staff.role || "",
    qualification: "",
    email: "",
    experience: "",
    expertise: ""
  };

  try {

    const response = await fetch(staff.link);

    if (!response.ok) {
      return details;
    }

    const html = await response.text();

    const parser = new DOMParser();

    const doc = parser.parseFromString(html, "text/html");

    const profileCard = doc.querySelector(".profile-card");

    if (!profileCard) {
      return details;
    }


    // NAME

    const nameElement = profileCard.querySelector("h2");

    if (nameElement) {
      details.name = nameElement.textContent.trim();
    }


    // DESIGNATION

    const designationElements =
      profileCard.querySelectorAll("h5");

    if (designationElements.length > 0) {

      details.role =
        designationElements[0].textContent.trim();

    }


    // EMAIL

    const emailElement =
      profileCard.querySelector('a[href^="mailto:"]');

    if (emailElement) {

      details.email =
        emailElement.textContent.trim();

    }


    // EXPERIENCE

    const paragraphs =
      profileCard.querySelectorAll("p");

    paragraphs.forEach(p => {

      const text =
        p.textContent.trim();

      if (
        text.toLowerCase().includes("serving sies") ||
        text.toLowerCase().includes("experience")
      ) {

        const numberMatch =
          text.match(/(\d+)\s*(?:years?|yrs?)/i);

        if (numberMatch) {

          details.experience =
            numberMatch[1];

        }

      }

    });


    // QUALIFICATION

    const qualificationSection =
      doc.querySelector("#qualification");

    if (qualificationSection) {

      const qualificationItems =
        qualificationSection.querySelectorAll(
          ".list-group-item"
        );

      const qualifications = [];

      qualificationItems.forEach(item => {

        const value =
          item.textContent.trim();

        if (value) {

          qualifications.push(value);

        }

      });

      details.qualification =
        qualifications.join(", ");

    }


    // EXPERT AREA

    const bodyText =
      profileCard.textContent;

    const expertMatch =
      bodyText.match(
        /Expert\s*Area\s*[:\-]\s*([\s\S]*?)(?=Experience|$)/i
      );

    if (expertMatch) {

      details.expertise =
        expertMatch[1]
          .replace(/\s+/g, " ")
          .trim();

    }

  } catch (error) {

    console.error(
      "Unable to load profile:",
      staff.link,
      error
    );

  }

  return details;
}


